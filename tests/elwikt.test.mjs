import test from 'node:test';
import assert from 'node:assert/strict';
import {rowsToEntryEl} from '../src/js/elwikt.js';
import {conjugate,finalizeEntry} from '../src/js/engine.js';

const T=s=>s.split('\n').map(l=>l.split('\t'));
const ROWS=T(`Εξακολουθητικοί χρόνοι
πρόσωπα	Ενεστώτας	Παρατατικός	Εξ. Μέλλ.	Υποτακτική	Προστακτική	Μετοχή
α' ενικ.	βρωμάω - βρωμώ	βρωμούσα	θα βρωμάω - βρωμώ	να βρωμάω - βρωμώ		βρωμώντας
β' ενικ.	βρωμάς	βρωμούσες	θα βρωμάς	να βρωμάς	βρώμα - βρώμαγε
γ' ενικ.	βρωμάει - βρωμά	βρωμούσε	θα βρωμάει - βρωμά	να βρωμάει - βρωμά	
α' πληθ.	βρωμάμε - βρωμούμε	βρωμούσαμε	θα βρωμάμε - βρωμούμε	να βρωμάμε - βρωμούμε	
β' πληθ.	βρωμάτε	βρωμούσατε	θα βρωμάτε	να βρωμάτε	βρωμάτε
γ' πληθ.	βρωμάν(ε) - βρωμούν(ε)	βρωμούσαν(ε)	θα βρωμάν(ε) - βρωμούν(ε)	να βρωμάν(ε) - βρωμούν(ε)	
Συνοπτικοί χρόνοι
πρόσωπα		Αόριστος	Συνοπτ. Μέλλ.	Υποτακτική	Προστακτική	Απαρέμφατο
α' ενικ.		βρώμησα	θα βρωμήσω	να βρωμήσω		βρωμήσει
β' ενικ.	βρώμησες	θα βρωμήσεις	να βρωμήσεις	βρώμα - βρώμησε
γ' ενικ.	βρώμησε	θα βρωμήσει	να βρωμήσει	
α' πληθ.	βρωμήσαμε	θα βρωμήσουμε	να βρωμήσουμε	
β' πληθ.	βρωμήσατε	θα βρωμήσετε	να βρωμήσετε	βρωμήστε
γ' πληθ.	βρώμησαν, βρωμήσαν(ε)	θα βρωμήσουν(ε)	να βρωμήσουν(ε)	
Συντελεσμένοι χρόνοι
πρόσωπα	Παρακείμενος	Υπερσυντέλικος	Συντελ. Μέλλ.	Υποτακτική	Προστακτική	
α' ενικ.	έχω βρωμήσει	είχα βρωμήσει	θα έχω βρωμήσει	να έχω βρωμήσει`);

test('βρωμώ dalla tabella greca', () => {
  const r=rowsToEntryEl(ROWS,'βρωμώ');
  assert.ok(r);
  const {entry,report}=r;
  assert.equal(entry.cls,'B1');
  assert.deepEqual(entry.O.pres,['βρωμάω / βρωμώ','βρωμάς','βρωμάει / βρωμά','βρωμάμε / βρωμούμε','βρωμάτε','βρωμάν(ε) / βρωμούν(ε)']);
  assert.equal(entry.O.impf[0],'βρωμούσα');
  assert.deepEqual(entry.O.aor,['βρώμησα','βρώμησες','βρώμησε','βρωμήσαμε','βρωμήσατε','βρώμησαν / βρωμήσαν(ε)']);
  assert.equal(entry.O.subj[0],'βρωμήσω');
  assert.deepEqual(entry.O.ipres,['βρώμα / βρώμαγε','βρωμάτε']);
  assert.deepEqual(entry.O.iaor,['βρώμα / βρώμησε','βρωμήστε']);
  assert.deepEqual(entry.O.ptc,['βρωμώντας']);
  assert.deepEqual(report.missing,[]);
  // l'archivio riesce a coniugarlo
  const v=conjugate(finalizeEntry(entry));
  assert.ok(v.some(x=>x.id==='act'));
});
test('senza tabella riconoscibile: null', () => {
  assert.equal(rowsToEntryEl(T('foo\tbar'),'βρωμώ'),null);
});
